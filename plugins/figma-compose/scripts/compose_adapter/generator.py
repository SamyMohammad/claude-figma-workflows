def content_hash(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':'),
        ensure_ascii=False, allow_nan=False).encode('utf-8')).hexdigest()


def generation_report(receipt, config):
    return {'tokenHash': receipt['tokenHash'], 'manifestHash': receipt['manifestHash'],
            'configHash': content_hash(config), 'allowedMaterialDefaults': config['allowedMaterialDefaults'],
            'materialDefaults': material_defaults(config),
            'precision': 'Compose Float channels, dp/sp and easing use IEEE-754 binary32; raw receipt retained unchanged.'}


def render_theme(receipt: dict, config: dict) -> dict[str, str]:
    for mode in receipt.get('resolvedByMode', {}).values():
        mode_names = [config.get('names', {}).get(path, _normalize(path)) for path in mode]
        if len(mode_names) != len(set(mode_names)):
            raise ComposeError('SYMBOL_COLLISION', 'Generated name collision')
    receipt, settings = load_inputs(receipt, config)
    defaults = material_defaults(settings)
    markers = {'colors': 'colorScheme:unmapped', 'typography': 'typography:unmapped', 'shapes': 'shapes:unmapped'}
    for group, roles in defaults.items():
        if markers[group] not in settings['allowedMaterialDefaults'] and set(roles) - set(settings['allowedMaterialDefaults']):
            raise ComposeError('MATERIAL_DEFAULT', 'Unmapped Material roles require explicit authorization')
    header = '// Generated by figma-compose; tracked by .workflow/compose-theme.json.\npackage ' + settings['packageName'] + '\n\n' + IMPORTS + '\n'
    modes = list(receipt['resolvedByMode'])
    paths = sorted(receipt['resolvedByMode'][modes[0]])
    shape_paths = set(settings['material']['shapes'].values())
    typed = {mode: {path: kotlin_value(tokens[path], settings, path in shape_paths)
                   for path in paths} for mode, tokens in receipt['resolvedByMode'].items()}
    properties = '\n'.join('    val ' + settings['names'][p] + ': ' + typed[modes[0]][p][0] + ',' for p in paths)
    tokens = 'data class AppTokens(\n' + properties + '\n)\n\nval LocalAppTokens = staticCompositionLocalOf<AppTokens> {\n    error("AppTheme is required")\n}\n'
    values = '\n\n'.join('internal val ' + mode + 'Tokens = AppTokens(\n' + '\n'.join(
        '    ' + settings['names'][p] + ' = ' + typed[mode][p][1] + ',' for p in paths) + '\n)' for mode in modes) + '\n'
    identity = 'object AppThemeIdentity {\n' + '\n'.join('    const val ' + key + ' = "' + value + '"' for key, value in
        [('tokenHash', receipt['tokenHash']), ('manifestHash', receipt['manifestHash']), ('configHash', content_hash(config))]) + '\n}\n'
    return {name: header + body for name, body in [('AppTokens.kt', tokens), ('AppTokenValues.kt', values),
            ('AppTheme.kt', theme_body(settings, modes)), ('AppThemeIdentity.kt', identity)]}
